// A rule is auto fixable when some of its findings carry a safe fix.
const AUTOFIX = new Set();
for (const file of ["images", "names", "forms", "document", "structure", "aria", "keyboard", "media", "contrast"]) {
  const src = readFileSync(`src/rules/${file}.ts`, "utf8");
  for (const block of src.split(/\r?\n {2}\{\r?\n {4}id: "/).slice(1)) {
    const id = block.slice(0, block.indexOf('"'));
    if (/safe: (true|sure|!!)/.test(block)) AUTOFIX.add(id);
  }
}
const rules = ruleList().map((r) => ({ ...r, wcagSlugs: SLUGS, autofix: AUTOFIX.has(r.id) }));

